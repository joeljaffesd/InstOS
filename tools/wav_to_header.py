#!/usr/bin/env python3
"""Mono 16-bit WAV -> C header (s16 samples).

    python3 tools/wav_to_header.py <wav> <header.h>
"""
import sys, os, wave, struct

src, dst = sys.argv[1], sys.argv[2]
w = wave.open(src, "rb")
assert w.getnchannels() == 1 and w.getsampwidth() == 2, "expect mono s16"
rate, n = w.getframerate(), w.getnframes()
samples = struct.unpack(f"<{n}h", w.readframes(n))

name = os.path.splitext(os.path.basename(dst))[0]
sym = name[0].upper() + name[1:]
with open(dst, "w") as f:
    f.write("#pragma once\n\n")
    f.write(f"// Generated by tools/wav_to_header.py from {os.path.basename(src)}\n\n")
    f.write(f"static constexpr unsigned {sym}Rate = {rate};\n")
    f.write(f"static constexpr unsigned {sym}Count = {n};\n")
    f.write(f"static const short {sym}PCM[{n}] = {{\n")
    for i in range(0, n, 16):
        f.write("    " + ", ".join(str(v) for v in samples[i:i + 16]) + ",\n")
    f.write("};\n")
print(f"{dst}: {n} samples at {rate} Hz")
