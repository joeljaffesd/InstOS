#!/usr/bin/env python3
"""JPEG/PNG -> RGB565 C header for C2DGraphics::DrawImage (DEPTH=16 raw pixels).

Uses macOS `sips` for decode+resize (no PIL dependency), parsing its BMP output.

    python3 tools/img_to_header.py <image> <header.h> <maxW> <maxH>
"""
import struct, subprocess, sys, tempfile, os, re

def main():
    src, dst, max_w, max_h = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])

    out = subprocess.check_output(["sips", "-g", "pixelWidth", "-g", "pixelHeight", src]).decode()
    w = int(re.search(r"pixelWidth: (\d+)", out).group(1))
    h = int(re.search(r"pixelHeight: (\d+)", out).group(1))
    scale = min(max_w / w, max_h / h, 1.0)
    tw, th = max(1, int(w * scale)), max(1, int(h * scale))

    with tempfile.TemporaryDirectory() as tmp:
        bmp = os.path.join(tmp, "img.bmp")
        subprocess.check_call(["sips", "-s", "format", "bmp", "-z", str(th), str(tw),
                               src, "--out", bmp], stdout=subprocess.DEVNULL)
        data = open(bmp, "rb").read()

    # BMP: BITMAPFILEHEADER (14) + BITMAPINFOHEADER
    off = struct.unpack_from("<I", data, 10)[0]
    hdr_size, bw, bh = struct.unpack_from("<Iii", data, 14)
    planes, bpp, comp = struct.unpack_from("<HHI", data, 26)
    assert comp == 0 and bpp in (24, 32), f"unsupported BMP: bpp={bpp} comp={comp}"
    top_down = bh < 0
    bh = abs(bh)
    stride = ((bw * bpp // 8) + 3) & ~3

    name = os.path.splitext(os.path.basename(dst))[0]
    sym = name[0].upper() + name[1:]
    px_per_line = 12
    with open(dst, "w") as f:
        f.write("#pragma once\n\n")
        f.write(f"// Generated by tools/img_to_header.py from {os.path.basename(src)}\n")
        f.write(f"// {bw} x {bh}, RGB565 raw pixels for C2DGraphics::DrawImage (DEPTH=16)\n\n")
        f.write(f"static constexpr unsigned {sym}Width = {bw};\n")
        f.write(f"static constexpr unsigned {sym}Height = {bh};\n")
        f.write(f"static const unsigned short {sym}Pixels[{bw * bh}] = {{\n")
        vals = []
        for y in range(bh):
            row = y if top_down else bh - 1 - y
            base = off + row * stride
            for x in range(bw):
                i = base + x * (bpp // 8)
                b, g, r = data[i], data[i + 1], data[i + 2]
                vals.append((r >> 3) << 11 | (g >> 2) << 5 | (b >> 3))
        for i in range(0, len(vals), px_per_line):
            f.write("    " + ", ".join(f"0x{v:04X}" for v in vals[i:i + px_per_line]) + ",\n")
        f.write("};\n")
    print(f"{dst}: {bw}x{bh}, {bw*bh*2} bytes")

main()
